"""Write main_flat.tex: main.tex with every \\input{tables/...} replaced by the file's content.

    ..\\.venv\\Scripts\\python.exe flatten.py

Single-file version for submission systems and for audit tools that do not follow \\input.
main.tex stays the source of truth; regenerate main_flat.tex after every edit.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "main.tex").read_text(encoding="utf-8")


def inline(m):
    p = m.group(1)
    p = p if p.endswith(".tex") else p + ".tex"
    body = (HERE / p).read_text(encoding="utf-8").rstrip("\n")
    return f"% >>> inlined from {p} (byte-identical copy of ../tables)\n{body}\n% <<< end {p}"


flat = re.sub(r"\\input\{([^}]+)\}", inline, src)
flat = "%% GENERATED by flatten.py from main.tex -- do not edit; edit main.tex and regenerate.\n" + flat
(HERE / "main_flat.tex").write_text(flat, encoding="utf-8")
print("wrote main_flat.tex,", len(re.findall(r"\\input\{", src)), "inputs inlined")
