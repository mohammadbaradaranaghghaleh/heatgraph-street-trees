"""Double-anonymised upload files, generated from main.tex (the single source of truth).

    ..\\.venv\\Scripts\\python.exe make_blind.py        (run inside manuscript/)
    -> manuscript_blind.tex   main.tex without authors, affiliations, e-mail, CRediT, PDF author metadata,
                              and with the repository URL (which contains an author's name) withheld
    -> title_page.tex         title, authors, affiliations, corresponding author, CRediT, declarations,
                              data and code availability with the repository URL
Compile both with tectonic. The script fails if any identifying string is left in the blind source.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "main.tex").read_text(encoding="utf-8")


def grab(pattern, text=src, flags=re.S):
    m = re.search(pattern, text, flags)
    if not m:
        sys.exit(f"pattern not found: {pattern[:60]}")
    return m


# ---------------------------------------------------------------- pieces of main.tex
title = grab(r"\\title\{(.*?)\}\n").group(1)
author_block = grab(r"(\\author\[.*?\\affiliation\[.*?\n\s*country=\{[^}]*\}\})\n").group(1)
credit = grab(r"(\\section\*\{CRediT authorship contribution statement\}.*?)(?=\n\\section\*)").group(1)
competing = grab(r"\\section\*\{Declaration of competing interest\}\n(.*?)\n\n").group(1)
funding = grab(r"\\section\*\{Funding\}\n(.*?)\n\n").group(1)
data = grab(r"\\section\*\{Data and code availability\}\n(.*?)\n\n").group(1)
ai = grab(r"\\section\*\{Declaration of generative AI[^}]*\}\n(.*?)\n\n").group(1)
url = grab(r"\\url\{(https://github\.com/[^}]*)\}", data).group(1)

authors = re.findall(r"\\author\[[^\]]*\]\{([^\\}]*)", author_block)
email = grab(r"\\ead\{([^}]*)\}", author_block).group(1)
corr = next(a for a in re.findall(r"\\author\[[^\]]*\]\{([^}]*\\corref[^}]*)\}", author_block))
corr = corr.split("\\corref")[0]
org = grab(r"organization=\{([^}]*)\}", author_block).group(1)
city = grab(r"city=\{([^}]*)\}", author_block).group(1)
country = grab(r"country=\{([^}]*)\}", author_block).group(1)

# ---------------------------------------------------------------- blind manuscript
blind = src
blind = blind.replace(author_block + "\n", "")
blind = re.sub(r"pdfauthor=\{[^}]*\}", "pdfauthor={}", blind)
blind = blind.replace(credit + "\n", "")
blind = blind.replace(f"\\url{{{url}}}", "a public repository (link withheld for double-anonymised review; "
                                          "provided on the title page)")
blind = blind.replace("Code and data are available to reviewers from the corresponding author on request.",
                      "Code and data are available to reviewers through the editor on request.")
blind = re.sub(r"\A(%%[^\n]*\n)+", "%% GENERATED by make_blind.py from main.tex -- double-anonymised version; "
                                    "do not edit.\n", blind)
blind = blind.replace(r"\pdfstringdefDisableCommands{\def\corref#1{}}" + "\n", "")

# anything identifying left?
low = blind.lower()
ident = [a for a in authors] + [email, url, "baradaran", "mehrabi", "yazdani", "islamic azad", "tehran",
                                "corresponding author", "credit authorship"]
left = [s for s in ident if s.lower() in low]
if left:
    sys.exit(f"identifying text left in blind manuscript: {left}")
(HERE / "manuscript_blind.tex").write_text(blind, encoding="utf-8")

# ---------------------------------------------------------------- title page
names = ", ".join(f"{a}\\textsuperscript{{a{',*' if a == corr else ''}}}" for a in authors)
credit_tp = credit.replace(r"\section*", r"\subsection*")
tp = rf"""%% GENERATED by make_blind.py from main.tex -- title page for double-anonymised submission; do not edit.
\documentclass[12pt]{{article}}
\usepackage{{iftex}}
\ifPDFTeX
  \usepackage[T1]{{fontenc}}
  \usepackage[utf8]{{inputenc}}
  \usepackage{{lmodern}}
\else
  \usepackage{{fontspec}}
\fi
\usepackage[a4paper,margin=2.5cm]{{geometry}}
\usepackage{{xurl}}
\usepackage[hidelinks]{{hyperref}}
\hypersetup{{pdftitle={{Title page}}}}
\setlength{{\parindent}}{{0pt}}
\setlength{{\parskip}}{{0.7em}}
\pagestyle{{empty}}
\begin{{document}}
{{\raggedright\Large\bfseries {title}\par}}

{names}

\textsuperscript{{a}}{org}, {city}, {country}

\textsuperscript{{*}}Corresponding author: {corr}, {org}, {city}, {country}. E-mail: \href{{mailto:{email}}}{{\nolinkurl{{{email}}}}}

\subsection*{{Acknowledgements}}
None.

{credit_tp}

\subsection*{{Declaration of competing interest}}
{competing}

\subsection*{{Funding}}
{funding}

\subsection*{{Data and code availability}}
{data}

\subsection*{{Declaration of generative AI and AI-assisted technologies in the writing process}}
{ai}
\end{{document}}
"""
(HERE / "title_page.tex").write_text(tp, encoding="utf-8")
print(f"wrote manuscript_blind.tex ({len(blind.splitlines())} lines) and title_page.tex; "
      f"authors: {', '.join(authors)}; corresponding: {corr} <{email}>")
