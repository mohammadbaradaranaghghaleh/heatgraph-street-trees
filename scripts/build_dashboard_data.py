"""Build dashboard_data/: the small, versioned subset of the results that app.py reads.

    .\\.venv\\Scripts\\python.exe scripts/build_dashboard_data.py

Reads data/processed/<patch>/ and data/stage5/ (from the release archive); writes dashboard_data/ only.
Per test patch:
  scene.npz    building heights, existing canopy, water, receptors, segment index, planting slots
  weather.csv  hourly forcing (for the hour selector)
  results.json benchmark rows, Pareto front, budgets (unchanged copy)
  designs.npz  X (66 benchmark layouts), front (Pareto layouts) as uint8, and
               dU = engine UTCI minus the no-new-tree run, int16 in units of 0.001 degC
The dashboard only displays tree-induced UTCI changes, so storing differences at 0.001 degC loses
nothing visible (max rounding error 0.0005 degC) and shrinks the arrays from ~87 MB to a few MB.
Rotterdam Centrum also gets the SOLWEIG verification arrays (unchanged copies). Revision results:
  revision_r2r3.json        practitioner heuristics and unseeded NSGA-III rows (per patch)
  heuristic_layouts.npz     practitioner-heuristic layouts + engine dU, same int16 format (per patch)
  revision_r4_verification.json, revision_round2_*.json   common-mask SOLWEIG comparison, conformal
                            coverage, per-district equity, sensitivity and seed stability (top level)
"""
import json
import shutil
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA, OUT = ROOT / "data", ROOT / "dashboard_data"
PATCHES = ["rot_centrum", "rot_kop_van_zuid", "rot_oude_westen", "xfer_freiburg_altstadt"]
SCENE_KEYS = ["building_heights", "base_canopy", "water_mask", "receptors", "seg_of_receptor", "slots"]
SCALE = 1000  # int16 units per degC


def main() -> int:
    for pid in PATCHES:
        src_p, src_s, dst = DATA / "processed" / pid, DATA / "stage5" / pid, OUT / pid
        dst.mkdir(parents=True, exist_ok=True)
        s = np.load(src_p / "scene.npz")
        np.savez_compressed(dst / "scene.npz", **{k: s[k] for k in SCENE_KEYS})
        shutil.copyfile(src_p / "weather.csv", dst / "weather.csv")
        shutil.copyfile(src_s / "results.json", dst / "results.json")
        d = np.load(src_s / "designs.npz")
        U = d["engine_utci"].astype(np.float64)
        dU = np.rint((U - U[0]) * SCALE)
        if np.abs(dU).max() >= np.iinfo(np.int16).max:
            print(f"{pid}: dUTCI out of int16 range")
            return 1
        np.savez_compressed(dst / "designs.npz", X=d["X"].astype(np.uint8), front=d["front"].astype(np.uint8),
                            dU=dU.astype(np.int16), scale=np.array(SCALE))
        err = np.abs(dU / SCALE - (U - U[0])).max()
        # revision results: practitioner heuristics + unseeded NSGA-III (rows), heuristic layouts (maps)
        shutil.copyfile(src_s / "revision_r2r3.json", dst / "revision_r2r3.json")
        h = np.load(src_s / "heuristic_layouts.npz")
        Uh = h["engine_utci"].astype(np.float64)
        dUh = np.rint((Uh - Uh[0]) * SCALE)
        if np.abs(dUh).max() >= np.iinfo(np.int16).max:
            print(f"{pid}: heuristic dUTCI out of int16 range")
            return 1
        np.savez_compressed(dst / "heuristic_layouts.npz", names=h["names"], X=h["X"].astype(np.uint8),
                            dU=dUh.astype(np.int16), scale=np.array(SCALE))
        mb = sum(f.stat().st_size for f in dst.iterdir()) / 1e6
        print(f"{pid}: {mb:.1f} MB, max dUTCI rounding error {err:.5f} degC")
    for f in ("solweig_verification_arrays.npz", "solweig_verification.json"):
        shutil.copyfile(DATA / "stage5" / "rot_centrum" / f, OUT / "rot_centrum" / f)
    for f in ("revision_r4_verification.json", "revision_round2_coverage.json", "revision_round2_equity.json",
              "revision_round2_sensitivity.json", "revision_round2_seeds.json"):
        shutil.copyfile(DATA / "stage5" / f, OUT / f)
    (OUT / "README.md").write_text(
        "Generated by `scripts/build_dashboard_data.py` from the released results; read by `app.py`.\n"
        "Do not edit by hand. Tree-induced UTCI changes are stored as int16 in units of 0.001 degC.\n",
        encoding="utf-8")
    total = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file()) / 1e6
    print(f"dashboard_data/: {total:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
